/**
 * 键集契约：`en-US.ts` 用它约束「一个键都不能少」。
 *
 * 叶子类型放宽成 `string`（而不是字面量）：否则英文文案会因为不等于中文原文而报类型错误。
 * 结构仍然严格——少一个键、多一个键都会编译失败。
 */
type WidenedStrings<T> = {
  [K in keyof T]: T[K] extends string ? string : WidenedStrings<T[K]>;
};

export type MessageSchema = WidenedStrings<typeof messages>;
